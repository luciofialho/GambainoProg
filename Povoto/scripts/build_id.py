# Pre-build script: generates src/BuildId.cpp with an id of the firmware being built.
# The id is the date/time at which the sources last changed plus a short hash of the sources
# (Povoto/src, Povoto/include and ../Common), so two builds of the same code have the same id
# and any edit gives a new one. Line endings are ignored in the hash.
Import("env")
import hashlib
import os
import re
import subprocess
from datetime import datetime

project = env.subst("$PROJECT_DIR")
out_path = os.path.join(project, "src", "BuildId.cpp")
roots = [os.path.join(project, "src"), os.path.join(project, "include"), os.path.join(project, "..", "Common")]
extensions = (".cpp", ".h", ".c", ".ino")

digest = hashlib.sha1()
for root in roots:
    paths = []
    for folder, dirs, names in os.walk(root):
        dirs[:] = [d for d in dirs if d not in (".pio", ".git")]
        for name in names:
            if name.endswith(extensions) and not (name == "BuildId.cpp" and folder == roots[0]):
                paths.append(os.path.join(folder, name))
    for path in sorted(paths):
        digest.update(os.path.relpath(path, root).replace("\\", "/").encode("utf-8"))
        with open(path, "rb") as f:
            digest.update(f.read().replace(b"\r", b""))
short = digest.hexdigest()[:8]


def git(*args):
    try:
        return subprocess.check_output(["git", "-C", project] + list(args), stderr=subprocess.DEVNULL).decode().strip()
    except Exception:
        return ""


commit = git("rev-parse", "--short", "HEAD") or "nogit"
dirty = "+dirty" if git("status", "--porcelain", "--", ".", "../Common") else ""
key = short + " " + commit + dirty

previous = ""
if os.path.exists(out_path):
    with open(out_path, "r") as f:
        found = re.search(r"// KEY (.*)", f.read())
        previous = found.group(1).strip() if found else ""

if previous == key:
    print("[build_id] unchanged: " + key)
else:
    stamp = datetime.now()
    build_id = stamp.strftime("%y%m%d-%H%M") + "-" + short
    info = stamp.strftime("%Y-%m-%d %H:%M") + " sources " + short + " git " + commit + dirty
    with open(out_path, "w", newline="\n") as f:
        f.write("// Generated by scripts/build_id.py at build time; not edited, not versioned.\n")
        f.write('#include "BuildId.h"\n')
        f.write('const char BUILD_ID[] = "' + build_id + '";\n')
        f.write('const char BUILD_INFO[] = "' + info + '";\n')
        f.write("// KEY " + key + "\n")
    print("[build_id] new id " + build_id + " (" + info + ")")
